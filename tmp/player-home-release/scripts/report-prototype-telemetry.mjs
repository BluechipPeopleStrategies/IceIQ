import fs from "node:fs";
import { ALL_ANIMATED_PLAYS } from "../src/play/playCatalog.js";
import {
  collectPlayTelemetrySnapshots,
  snapshotHasForbiddenYoungLanguage,
} from "../src/play/prototypeTelemetry.js";

const ageBands = [
  "U7 - Playground",
  "U9 - Explorer",
  "U11 - The Trainer",
  "U13 - The Reader",
  "U15 - Film Room",
  "U18 - Film Room",
];

const snapshots = ALL_ANIMATED_PLAYS.flatMap((play) =>
  ageBands.flatMap((ageBand) => collectPlayTelemetrySnapshots(play, ageBand))
);

const warnings = snapshots
  .filter(snapshotHasForbiddenYoungLanguage)
  .map((snapshot) => ({
    playId: snapshot.playId,
    nodeId: snapshot.nodeId,
    ageBand: snapshot.ageBand,
    question: snapshot.displayedQuestion,
  }));

let md = "# Prototype Telemetry Report\n\n";
md += "Generated by `npm run report:prototype-telemetry`.\n\n";
md += `- **Plays checked:** ${ALL_ANIMATED_PLAYS.length}\n`;
md += `- **Age bands checked:** ${ageBands.length}\n`;
md += `- **Snapshots generated:** ${snapshots.length}\n`;
md += `- **Warnings:** ${warnings.length}\n\n`;

md += "## What This Tracks\n\n";
md += "Each snapshot records the actual player-facing question, answer options, reveal text, cue label, correct option id, terminal state, and a deterministic question signature.\n\n";

md += "## Warnings\n\n";
if (!warnings.length) {
  md += "_No telemetry language warnings._\n\n";
} else {
  for (const warning of warnings) {
    md += `- **${warning.playId}** / ${warning.nodeId} / ${warning.ageBand}: ${warning.question}\n`;
  }
  md += "\n";
}

md += "## Sample Snapshots\n\n";
for (const snapshot of snapshots.slice(0, 12)) {
  md += `### ${snapshot.playTitle} / ${snapshot.nodeId} / ${snapshot.ageBand}\n\n`;
  md += `- **Signature:** ${snapshot.questionSignature}\n`;
  md += `- **Question:** ${snapshot.displayedQuestion || "_terminal reveal_"}\n`;
  if (snapshot.displayedCue) md += `- **Cue:** ${snapshot.displayedCue}\n`;
  if (snapshot.options.length) {
    md += "- **Options:**\n";
    for (const option of snapshot.options) {
      md += `  - ${option.isCorrect ? "✅" : "○"} ${option.displayedText}`;
      if (option.displayedRevealText) md += ` — ${option.displayedRevealText}`;
      md += "\n";
    }
  }
  md += "\n";
}

fs.writeFileSync("docs/prototype-telemetry-report.md", md, "utf8");

console.log("Wrote docs/prototype-telemetry-report.md");
console.log("Snapshots:", snapshots.length);
console.log("Warnings:", warnings.length);

if (warnings.length) process.exitCode = 1;
