import fs from "node:fs";
import path from "node:path";

const ROOTS = ["src", "docs"];
const OUT_JSON = "docs/animated-retrofit-candidates.json";
const OUT_MD = "docs/animated-retrofit-candidates.md";

const EXCLUDE_DIRS = new Set([
  "node_modules",
  "dist",
  ".git",
  "images",
  "archive",
  "reviewed",
]);

const INCLUDE_EXT = new Set([
  ".js",
  ".jsx",
  ".mjs",
  ".json",
  ".md",
]);

const highFitTerms = [
  "2-on-1",
  "2v1",
  "odd-man",
  "rush",
  "gap control",
  "gap-control",
  "angling",
  "steer",
  "forecheck",
  "backcheck",
  "off-puck",
  "support",
  "passing lane",
  "shot lane",
  "defender",
  "puck carrier",
  "pressure",
  "breakout",
  "entry",
  "transition",
  "middle lane",
  "weak side",
  "back door",
  "backdoor",
];

const variantTerms = [
  "backchecker",
  "falls",
  "fall",
  "poor angle",
  "bad angle",
  "late",
  "recover",
  "overcommit",
  "cheat",
  "covered",
  "blocked",
  "delay",
  "second read",
  "subsequent",
  "trailer",
];

const staticTerms = [
  "definition",
  "vocabulary",
  "term",
  "principle",
  "rule",
  "true or false",
];

function walk(dir, files = []) {
  if (!fs.existsSync(dir)) return files;

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (EXCLUDE_DIRS.has(entry.name)) continue;

    const full = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      walk(full, files);
    } else if (INCLUDE_EXT.has(path.extname(entry.name))) {
      files.push(full);
    }
  }

  return files;
}

function countTerms(text, terms) {
  const lower = text.toLowerCase();
  return terms.filter((term) => lower.includes(term.toLowerCase()));
}

function firstSnippet(text, terms) {
  const lines = text.split(/\r?\n/);
  const lowerTerms = terms.map((term) => term.toLowerCase());

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const lower = line.toLowerCase();
    if (lowerTerms.some((term) => lower.includes(term))) {
      return {
        line: i + 1,
        text: line.trim().slice(0, 220),
      };
    }
  }

  return { line: 1, text: lines[0]?.trim().slice(0, 220) || "" };
}

function classify(file, text) {
  const highMatches = countTerms(text, highFitTerms);
  const variantMatches = countTerms(text, variantTerms);
  const staticMatches = countTerms(text, staticTerms);

  const score = highMatches.length * 3 + variantMatches.length * 2 - staticMatches.length;

  let fit = "keep-static";
  if (score >= 12) fit = "high-animation-fit";
  else if (score >= 6) fit = "possible-animation-fit";
  else if (variantMatches.length >= 2 && highMatches.length >= 1) fit = "variant-candidate";

  let suggestedUse = "Keep as static quiz/study content";
  if (fit === "high-animation-fit") suggestedUse = "Convert into full animated scenario";
  if (fit === "possible-animation-fit") suggestedUse = "Review for possible animated scenario";
  if (fit === "variant-candidate") suggestedUse = "Use as a harder variant of an existing animated play";

  const snippet = firstSnippet(text, [...highFitTerms, ...variantTerms, ...staticTerms]);

  return {
    file,
    fit,
    score,
    suggestedUse,
    matchedAnimationTerms: highMatches,
    matchedVariantTerms: variantMatches,
    matchedStaticTerms: staticMatches,
    snippet,
  };
}

const files = ROOTS.flatMap((root) => walk(root));
const results = files
  .map((file) => {
    const text = fs.readFileSync(file, "utf8").replace(/^\uFEFF/, "");
    return classify(file, text);
  })
  .filter((result) => result.score >= 2 || result.fit !== "keep-static")
  .sort((a, b) => b.score - a.score || a.file.localeCompare(b.file));

fs.writeFileSync(OUT_JSON, JSON.stringify(results, null, 2) + "\n", "utf8");

const groups = [
  ["high-animation-fit", "High Animation Fit"],
  ["variant-candidate", "Variant Candidates"],
  ["possible-animation-fit", "Possible Animation Fit"],
  ["keep-static", "Likely Static / Low Fit"],
];

let md = `# Animated Retrofit Candidates

Generated by \`scripts/audit-animated-retrofit-candidates.mjs\`.

Purpose: identify existing IceIQ/RinkReads questions, scenarios, and docs that may be worth converting into animated play kernels or variants.

## How To Use This

- High animation fit: likely worth converting into a full animated scenario.
- Variant candidates: likely useful as harder versions of an existing scenario.
- Possible animation fit: review manually.
- Likely static: probably keep as non-animated quiz/study content.

`;

for (const [fit, title] of groups) {
  const items = results.filter((result) => result.fit === fit);
  md += `\n## ${title}\n\n`;

  if (!items.length) {
    md += `_No candidates found._\n`;
    continue;
  }

  for (const item of items.slice(0, 50)) {
    md += `### ${item.file}\n\n`;
    md += `- **Score:** ${item.score}\n`;
    md += `- **Suggested use:** ${item.suggestedUse}\n`;
    md += `- **Matched animation terms:** ${item.matchedAnimationTerms.join(", ") || "none"}\n`;
    md += `- **Matched variant terms:** ${item.matchedVariantTerms.join(", ") || "none"}\n`;
    md += `- **Snippet:** line ${item.snippet.line}: ${item.snippet.text || "_No snippet_"}\n\n`;
  }
}

fs.writeFileSync(OUT_MD, md, "utf8");

console.log(`Audited ${files.length} files.`);
console.log(`Wrote ${OUT_JSON}`);
console.log(`Wrote ${OUT_MD}`);
console.log(`Candidates found: ${results.length}`);
