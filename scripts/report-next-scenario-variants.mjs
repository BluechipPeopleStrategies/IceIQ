function implementedTitleSet() {
  return new Set(
    ALL_ANIMATED_PLAYS.map((play) => String(play.title || "").toLowerCase())
  );
}

const implementedTitles = implementedTitleSet();

const NEW_KINDS = ["verdict", "predict-next", "spot-mistake"];

let md = "# Next Scenario Variants\n\n";
md += "Generated by `npm run report:next-variants`.\n\n";
md += "This queue turns scenario families into buildable play variants.\n\n";

const nextItems = [];

for (const family of report.families) {
  const backlog = variantBacklog[family.id] || [];
  const missing = backlog.filter((item) => !implementedTitles.has(item.title.toLowerCase()));
  const next = missing.sort((a, b) => a.priority - b.priority)[0];

  md += `## ${family.title}\n\n`;
  md += `- **Implemented:** ${family.count}/${family.targetVariants}\n`;
  md += `- **Current status:** ${family.count >= family.targetVariants ? "complete" : "needs variants"}\n\n`;

  if (!next) {
    md += "_No queued variant needed right now._\n\n";
    continue;
  }

  nextItems.push({ familyId: family.id, familyTitle: family.title, ...next });

  const missingKind = NEW_KINDS.find((k) => !(family.kindCounts || {})[k]) || "read-mc";

  md += "### Next Recommended Variant\n\n";
  md += `- **Title:** ${next.title}\n`;
  md += `- **Cue:** ${next.cue}\n`;
  md += `- **Decision:** ${next.decision}\n`;
  md += `- **Common mistake:** ${next.mistake}\n`;
  md += `- **Format:** ${next.format}\n`;
  md += `- **Recommended kind:** ${missingKind}\n\n`;

  md += "### Remaining Backlog\n\n";
  for (const item of missing) {
    md += `- ${item.priority}. **${item.title}** — ${item.cue}\n`;
  }
  md += "\n";
}

md += "## Build Recommendation\n\n";

if (!nextItems.length) {
  md += "All tracked backlog items are already implemented. Add new family plans before generating more plays.\n";
} else {
  const top = nextItems[0];
  md += `Build next: **${top.title}** in **${top.familyTitle}**.\n\n`;
  md += "Why this one first:\n\n";
  md += "- It strengthens the most important active family.\n";
  md += "- It changes one meaningful cue.\n";
  md += "- It can stay as one question plus reveal.\n";
  md += "- It avoids disconnected second-question logic.\n";
}

fs.writeFileSync("docs/factory/next-scenario-variants.md", md, "utf8");

console.log("Wrote docs/factory/next-scenario-variants.md");
console.log("Next queued variants:", nextItems.length);
