import fs from "node:fs";
import { ALL_ANIMATED_PLAYS } from "../src/play/playCatalog.js";
import {
  buildScenarioFamilyReport,
  familyCompletionLabel,
} from "../src/play/playFamilies.js";

const report = buildScenarioFamilyReport(ALL_ANIMATED_PLAYS);

let md = "# Scenario Families Report\n\n";
md += "Generated by `npm run report:scenario-families`.\n\n";
md += `- **Plays checked:** ${ALL_ANIMATED_PLAYS.length}\n`;
md += `- **Families tracked:** ${report.families.length}\n`;
md += `- **Unclassified plays:** ${report.unclassified.length}\n`;
md += `- **Warnings:** ${report.warnings.length}\n\n`;

md += "## Family Progress\n\n";
md += "| Family | Status | Implemented | Target |\n";
md += "|---|---:|---:|---:|\n";

for (const family of report.families) {
  md += `| ${family.title} | ${familyCompletionLabel(family)} | ${family.count} | ${family.targetVariants} |\n`;
}

md += "\n## Families\n\n";

for (const family of report.families) {
  const kindLine = Object.entries(family.kindCounts || {})
    .map(([kind, n]) => `${kind}: ${n}`)
    .join(", ");

  md += `### ${family.title}\n\n`;
  md += `${family.description}\n\n`;
  md += `- **Family ID:** \`${family.id}\`\n`;
  md += `- **Implemented:** ${family.count}\n`;
  md += `- **Target variants:** ${family.targetVariants}\n`;
  md += `- **Kinds:** ${kindLine || "none"}\n\n`;

  md += "**Teaching arc**\n\n";
  for (const step of family.teachingArc) {
    md += `- ${step}\n`;
  }

  md += "\n**Implemented plays**\n\n";
  if (!family.plays.length) {
    md += "_No implemented plays yet._\n\n";
  } else {
    for (const play of family.plays) {
      md += `- **${play.title}** — \`${play.id}\`\n`;
    }
    md += "\n";
  }
}

md += "## Warnings\n\n";
if (!report.warnings.length) {
  md += "_No warnings._\n\n";
} else {
  for (const warning of report.warnings) {
    md += `- **${warning.familyId}:** ${warning.message}\n`;
  }
  md += "\n";
}

md += "## How To Use This\n\n";
md += "- Families define what a player is learning over repeated variants.\n";
md += "- A new play should belong to a family unless it starts a new family.\n";
md += "- Variants should change one meaningful cue, not just move tokens around.\n";
md += "- The factory should grow weak families before creating random new concepts.\n";

fs.writeFileSync("docs/scenario-families-report.md", md, "utf8");

console.log("Wrote docs/scenario-families-report.md");
console.log("Unclassified:", report.unclassified.length);
console.log("Warnings:", report.warnings.length);

if (report.unclassified.length) process.exitCode = 1;
