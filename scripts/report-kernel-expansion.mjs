// Expand every play kernel, gate the candidates (validators + novelty vs the
// live catalog), and write the staging report the factory promotes from.
// No generated play enters the catalog here — the Bulk-Assisted Creation Rule
// (batch cap 3 + manual playtest) governs promotion.
// Usage: npm run report:kernel-expansion
import { writeFileSync } from "node:fs";
import { expandTwoOnOneFamily } from "../src/play/kernels/twoOnOneKernel.js";
import { validateAnimatedPlay } from "../src/play/validateAnimatedPlay.js";
import { validateFactoryStandards } from "../src/play/validateFactoryStandards.js";
import { filterNovel, answerSignature } from "../src/play/noveltyGate.js";
import { ALL_ANIMATED_PLAYS } from "../src/play/playCatalog.js";

const KERNELS = [{ name: "twoOnOne", expand: expandTwoOnOneFamily }];

const lines = [];
lines.push("# Kernel Expansion Report");
lines.push("");
lines.push("Generated by `npm run report:kernel-expansion`. Staging only: promotion");
lines.push("into the catalog goes through the bulk-batch process (cap 3, manual");
lines.push("playtest) per `docs/play-kernel-standards.md`.");
lines.push("");

for (const kernel of KERNELS) {
  const candidates = kernel.expand();
  const validatorPass = [];
  const validatorFail = [];
  for (const play of candidates) {
    const a = validateAnimatedPlay(play);
    const f = validateFactoryStandards(play);
    const errs = [...(a.errors || []), ...(f.errs || [])];
    if (errs.length) validatorFail.push({ play, errs });
    else validatorPass.push(play);
  }
  const { kept, rejected } = filterNovel(validatorPass, ALL_ANIMATED_PLAYS);

  lines.push(`## Kernel: ${kernel.name}`);
  lines.push("");
  lines.push(`- Candidates expanded: **${candidates.length}**`);
  lines.push(`- Validator-clean (animated-play + factory standards): **${validatorPass.length}**`);
  lines.push(`- Survived the novelty gate vs the live catalog: **${kept.length}**`);
  lines.push(`- Pruned as clones / over cap: ${rejected.length} (logged below, never silent)`);
  lines.push("");
  lines.push("### Ready tray (novel, validator-clean, awaiting batch promotion)");
  lines.push("");
  lines.push("| id | signature | params |");
  lines.push("|---|---|---|");
  for (const p of kept) {
    lines.push(`| \`${p.id}\` | ${answerSignature(p)} | ${JSON.stringify(p.generated.params)} |`);
  }
  lines.push("");
  if (validatorFail.length) {
    lines.push("### Validator failures");
    lines.push("");
    for (const { play, errs } of validatorFail) lines.push(`- \`${play.id}\`: ${errs.join("; ")}`);
    lines.push("");
  }
  lines.push("### Pruned (reason)");
  lines.push("");
  for (const { play, reason } of rejected) lines.push(`- \`${play.id}\` — ${reason}`);
  lines.push("");
}

writeFileSync("docs/factory/kernel-expansion-report.md", lines.join("\n") + "\n");
console.log("Wrote docs/factory/kernel-expansion-report.md");
